"""Generates Solver/HuntJourneys.cs from Faloop's web client bundle.

Faloop's zone data has the spawn points of hunt marks ("mob" POIs), each with a
journeyPoiId that points to the aetheryte or zone boundary to start from.

Usage:
    python3 generate_hunt_journeys.py <path to Faloop's main.*.js>

The Faloop zone ID to TerritoryType ID mapping is read from
FaloopIntegration/Faloop/FaloopEmbedData.cs.
"""

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
EMBED_DATA = ROOT / "FaloopIntegration" / "Faloop" / "FaloopEmbedData.cs"
OUTPUT = ROOT / "AetheryteLinkInChat" / "Solver" / "HuntJourneys.cs"

ZONE_PATTERN = re.compile(r'\{id:"([a-z_]+)",name:\{[^{}]*\},expansionId:"[a-z_]+",territoryId:"[a-z_]+",map:\{[^{}]*\{[^{}]*\}[^{}]*\},pois:\[')
POI_PATTERN = re.compile(r'\{id:(\d+),(?:name:\{[^{}]*\},)?type:"(\w+)",location:"(\d+),(\d+)"(?:,journeyPoiId:(\d+))?')


def read_territory_types() -> dict[str, int]:
    text = EMBED_DATA.read_text(encoding="utf-8-sig")
    start = text.index("TerritoryTypes = ")
    end = text.index("});", start)
    return {zone: int(territory) for zone, territory in re.findall(r'\{"([a-z_]+)", (\d+)\}', text[start:end])}


def extract_array(text: str, start: int) -> str:
    """Returns the contents of the array literal that starts right after `start`."""
    depth = 1
    for i in range(start, len(text)):
        if text[i] == "[":
            depth += 1
        elif text[i] == "]":
            depth -= 1
            if depth == 0:
                return text[start:i]
    raise ValueError("unterminated array")


def main() -> None:
    bundle = pathlib.Path(sys.argv[1]).read_text(encoding="utf-8")
    territory_types = read_territory_types()

    lines = []
    for zone_match in ZONE_PATTERN.finditer(bundle):
        zone = zone_match.group(1)
        territory = territory_types.get(zone)
        if territory is None:
            print(f"skip unknown zone: {zone}", file=sys.stderr)
            continue

        pois = {}
        for poi in POI_PATTERN.finditer(extract_array(bundle, zone_match.end())):
            poi_id, poi_type, x, y, journey = poi.groups()
            pois[int(poi_id)] = (poi_type, int(x), int(y), int(journey) if journey else None)

        journeys = []
        for poi_type, x, y, journey in pois.values():
            if poi_type != "mob" or journey is None or journey not in pois:
                continue
            _, journey_x, journey_y, _ = pois[journey]
            journeys.append(f"new({x}, {y}, {journey_x}, {journey_y})")

        if journeys:
            lines.append(f"        // {zone}")
            lines.append(f"        {{{territory}, [{', '.join(journeys)}]}},")

    OUTPUT.write_text(
        "﻿// <auto-generated>\n"
        "// Generated by Scripts/generate_hunt_journeys.py from Faloop's web client. Do not edit manually.\n"
        "// </auto-generated>\n"
        "\n"
        "using System.Collections.Generic;\n"
        "using System.Collections.ObjectModel;\n"
        "\n"
        "namespace Divination.AetheryteLinkInChat.Solver;\n"
        "\n"
        "public static class HuntJourneys\n"
        "{\n"
        "    // TerritoryType ID => spawn points of hunt marks and the points to start from, in raw map coordinates (0-2048)\n"
        "    public static readonly ReadOnlyDictionary<uint, HuntJourney[]> Journeys = new(new Dictionary<uint, HuntJourney[]>\n"
        "    {\n"
        + "\n".join(lines)
        + "\n    });\n"
        "}\n",
        encoding="utf-8",
        newline="\r\n",
    )


if __name__ == "__main__":
    main()
